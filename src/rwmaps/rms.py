_HEADER = """\
/* {title}
 *
 * Real-world coastline encoded as create_land blocks, so this script is
 * self-contained: no companion .scx, no game files touched, and the engine
 * transfers it to other players automatically in multiplayer.
 *
 * Generated by rwmaps -- projection {projection}, {size}x{size} tiles
 */
"""

