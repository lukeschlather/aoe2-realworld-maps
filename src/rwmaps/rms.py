@dataclass
class RmsOptions:
    """Terrain and object choices that go with a biome."""

    land: str = "GRASS"
    land_alt: str = "GRASS3"
    land_alt2: str = "DIRT3"
    forest: str = "FOREST"
    tree: str = "OAKTREE"
    forest_percent: int = 10
    #: How many separate clumps the map-wide forest is broken into.
    #: Exposed as a knob (it was hardcoded at 12); the default is unchanged.
    #:
    #: NEGATIVE RESULT, recorded so it is not re-tried: raising this does
    #: **not** even out wood between players. Britain shows a large spread
    #: in "share of my nearby land that is forest" - and it barely moves
    #: with clump count (one sample each, Britain, everything else fixed):
    #:
    #: | clumps | forest share across the 8 players |
    #: |--------|-----------------------------------|
    #: | 12     | 0.07 - 0.53                       |
    #: | 30     | 0.01 - 0.43                       |
    #: | 60     | 0.06 - 0.52                       |
    #:
    #: The cause is upstream: ``land_percent`` is a share of the *whole
    #: map's* land, and on a fragmented region players have very different
    #: amounts of land near them, so a single clump dominates the share of
    #: whoever is on a small island. Granularity cannot fix a denominator
    #: problem.
    #:
    #: The stock answer is ``includes/forest.inc``, which budgets a forest
    #: per player (``PLAYER_FOREST_TILES``, ``PLAYER_FOREST_AVOIDANCE``,
    #: ``PLAYER_FOREST_TEAM_DEDUCTION``). It builds off a per-player
    #: ``SPAWN_PLACEHOLDER`` terrain that ``rms_land`` does not paint, so
    #: adopting it is a land-generation change rather than a resource one.
    #: MEASURED SINCE, against a different question: clump count is exactly
    #: the knob for forest *structure*, which is what "the map plays like
    #: Black Forest" is about, and structure was never what the sweep above
    #: looked at. At 12 clumps the wood comes out as a handful of masses -
    #: our regions measure 16-75 blobs with the single largest holding
    #: 20-52% of all the wood on six of eleven, against stock Arabia's 126
    #: blobs and 2%. Stock Black Forest is the other pole at 44%, so on that
    #: axis several of our regions sit next to Black Forest rather than next
    #: to an open map. See ``automation/forest_structure.py``.
    forest_clumps: int = 12
    #: How ragged each clump is. Lower disperses a clump into fingers and
    #: gaps rather than one solid mass; the engine default is around 10 and
    #: the land generator here uses 8 for coastline blobs. This is the
    #: second half of the structure knob - clump *count* decides how many
    #: woods there are, this decides whether a wood is walkable through.
    #: ``None`` leaves the clause out entirely, which is the behaviour every
    #: map shipped so far.
    forest_clumping_factor: int | None = None
    #: Whether the map-wide forest avoids player start areas.
    #:
    #: This pushes wood AWAY from players and into whatever land nobody
    #: starts on. On a region like Britain that land is France and the
    #: Scandinavian corner, and the result is a map that is simultaneously
    #: the most densely wooded one measured (0.256 forest share of land,
    #: same as jungle-map Yucatan) and the most wood-POOR per player
    #: (mean 127 reachable forest tiles, below every stock map measured,
    #: with one player on 37). 3361 of its forest tiles sit where no player
    #: can reach them at all.
    #:
    #: Density and adequacy are different questions. This knob looked like
    #: the one that separates them - move wood toward players without
    #: changing how much of it there is.
    #:
    #: NEGATIVE RESULT, recorded so it is not re-tried: turning it off is
    #: catastrophic. ``set_avoid_player_start_areas`` is not a nicety, it is
    #: what stops forest spawning *on top of* a start. Measured, one sample
    #: each, everything else held constant:
    #:
    #: | condition          | wood/player      | open tiles | players w/ nothing |
    #: |--------------------|------------------|------------|--------------------|
    #: | Britain avoid=on   | 37-247 (mean127) | 707-1111   | 0 of 8             |
    #: | Britain avoid=OFF  | 0-108 (mean 23)  | 0-474      | 7 of 8             |
    #: | Greece  avoid=on   | 151-236 (mean180)| 741-1217   | 0 of 8             |
    #: | Greece  avoid=OFF  | 0-224 (mean 145) | 0-1075     | 2 of 8             |
    #:
    #: Players are entombed in trees - the "walled in by wood" failure this
    #: project has seen reported in the wild, reproduced on demand. Note it
    #: also made wood *worse*, not better: unclaimed forest went UP (3361 ->
    #: 5605 on Britain), because forest that lands on a start blocks the
    #: player off from the rest of their own wood.
    #:
    #: The stock mechanism is different in a way that matters: forest.inc
    #: budgets a forest per player and keeps it ``PLAYER_FOREST_AVOIDANCE``
    #: (6-9) tiles off the town centre - "cluster near the start but not on
    #: it", where this flag only offers "near" or "avoid the start area
    #: entirely". Getting that behaviour needs the per-player
    #: SPAWN_PLACEHOLDER terrain rms_land does not paint yet.
    forest_avoid_starts: bool = True
    max_elevation: int = 7
    elevation_clumps: int = 8
    elevation_tiles: int = 600
    elevation: bool = True

    #: Legacy only - the additive close-range gold/stone/deer/boar block
    #: that backstopped the 1999 include's silent placement failures. It has
    #: no meaning under System A, which fixes the cause rather than papering
    #: over it (``find_closest``/``require_path``/tile shuffling instead of
    #: one-shot placement), and RESOURCE_TEMPLATES.md is explicit that the
    #: modern equivalent *replaces* this rather than stacking with it.
    tight_resource_backstop: bool = False

    #: Give each player their own budgeted forest next to their start, on
    #: top of the map-wide one. See ``build_per_player_forest`` - this is
    #: the only lever found that raises the WORST player's reachable wood
    #: rather than just moving the average around.
    per_player_forest: bool = True
    #: Tiles and clumps for that forest, per player. The player's own land
    #: is PLAYER_LAND_TILES (240), so the budget has to fit inside it with
    #: room left for the town centre and its resources.
    player_forest_tiles: int = 100
    player_forest_clumps: int = 3

    #: System A configuration. Ignored on the legacy path.
    pins: ThemePins = field(default_factory=ThemePins)
    flavor: ResourceFlavor = field(default_factory=ResourceFlavor)


